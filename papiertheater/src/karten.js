// Projektion: v = {lon, lat, s (px pro Breitengrad), x, y}
const COSR = Math.cos(46 * Math.PI / 180);
function proj(v, lon, lat) { return [v.x + (lon - v.lon) * v.s * COSR, v.y - (lat - v.lat) * v.s]; }
function projAll(v, pts) { return pts.map(([a, b]) => proj(v, a, b)); }

